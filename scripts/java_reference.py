class GeneratorError(Exception):
    """A missing prerequisite or a failed Java run; main() prints it as one ``error:`` line."""


def check_prerequisites(java_dir: Path) -> None:
    for tool in ("java", "javac"):
        if shutil.which(tool) is None:
            raise GeneratorError(f"{tool} not found on PATH; a JDK (11 or later) is required "
                                 "(the Apptainer image has none: run this on the host)")
    java_dir = Path(java_dir)
    if not (java_dir / "uk").is_dir():
        raise GeneratorError(f"no Java sources at {java_dir / 'uk'}; pass --java-dir pointing at "
                             "the Junction_Mapper checkout")
    if not list((java_dir / "lib").glob("*.jar")):
        raise GeneratorError(f"no jars in {java_dir / 'lib'}; the Java checkout's lib/ is required "
                             "(see its CLAUDE.md for how to re-fetch it)")


def _inside(child: Path, parent: Path) -> bool:
    child, parent = child.resolve(), parent.resolve()
    return child == parent or parent in child.parents


def compile_java(java_dir: Path, work_dir: Path, rebuild: bool = False) -> Path:
    """Compile the Java sources plus the driver into ``work_dir/classes``; return that directory."""
    java_dir, work_dir = Path(java_dir).resolve(), Path(work_dir).resolve()
    if _inside(work_dir, java_dir):
        raise GeneratorError(f"--work-dir {work_dir} is inside the Java checkout {java_dir}; the "
                             "Java tree is a read-only oracle, pick a scratch directory elsewhere")
    classes = work_dir / "classes"
    marker = classes / "DRIVER_BUILT"
    if marker.exists() and not rebuild:
        return classes
    src = work_dir / "driver_src" / Path(*DRIVER_CLASS.split(".")).with_suffix(".java")
    src.parent.mkdir(parents=True, exist_ok=True)
    src.write_text(DRIVER_SOURCE, encoding="utf-8")
    classes.mkdir(parents=True, exist_ok=True)
    files = sorted(str(p) for p in (java_dir / "uk").rglob("*.java")) + [str(src)]
    cmd = ["javac", "-encoding", "ISO-8859-1", "-nowarn", "-cp", f"{java_dir / 'lib'}/*",
           "-d", str(classes), *files]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        tail = " | ".join(proc.stderr.strip().splitlines()[-3:])
        raise GeneratorError(f"javac failed: {tail}")
    marker.write_text("ok\n")
    return classes


# ---- the synthetic rectilinear control ----------------------------------------------------------

def make_control(out_dir: Path) -> tuple[Path, Path]:
    """Write ``control_grid.tif`` (RGB, random content, fixed seed) and its label ``.npy``.

    A 3 x 3 grid of rectangles of unequal sizes in a 130 x 150 field. The centre cell has four
    straight sides and eight neighbours, far from the border: its interfaces are the rectilinear
    rows whose integer metrics must match the Java exactly.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    lab = np.zeros((130, 150), np.int32)
    k = 1
    for r0, r1 in ((15, 45), (45, 85), (85, 115)):
        for c0, c1 in ((15, 55), (55, 100), (100, 135)):
            lab[r0:r1, c0:c1] = k
            k += 1
    rng = np.random.default_rng(16)
    img = rng.integers(0, 256, size=(130, 150, 3), dtype=np.uint8)
    tif, npy = out_dir / "control_grid.tif", out_dir / "control_grid.JM1.npy"
    Image.fromarray(img, "RGB").save(tif, format="TIFF")
    np.save(npy, lab)
    return tif, npy


# ---- running the Java ---------------------------------------------------------------------------

def choose_cells(view: np.ndarray, dilation: int, wanted: list[int] | None, n: int | None) -> list[int]:
    """Cell ids to click: ``wanted`` if given, else the first ``n`` with a safe margin."""
    margin = dilation + 3
    h, w = view.shape
    ok = []
    for cid in (int(c) for c in np.unique(view) if c != 0):
        rr, cc = np.nonzero(view == cid)
        if len(rr) >= 40 and rr.min() >= margin and cc.min() >= margin \
                and rr.max() < h - margin and cc.max() < w - margin:
            ok.append(cid)
    if wanted is not None:
        missing = [c for c in wanted if c not in ok]
        if missing:
            raise GeneratorError(f"cells {missing} are absent, too small or too close to the image "
                                 f"border (need >= {margin} px clear and >= 40 px of area)")
        return list(wanted)
    return ok if n is None else ok[:n]


def seed_for(view: np.ndarray, cid: int) -> tuple[int, int]:
    """(x, y) = (col, row) of the pixel deepest inside the cell: a click that surely floods it.

    Ties are normal (14 pixels share the maximum in the control grid's centre cell); the one
    chosen is the smallest row, then the smallest column, which is what ``argmax`` returns.
    The Java's flood, and so its edge pixels, convex hull and corners, depend on the click
    (README.md "Why the click matters"); this fixed rule makes the generator deterministic and
    the click is written to every row as seed_row / seed_col.
    """
    dt = ndimage.distance_transform_edt(view == cid)
    r, c = np.unravel_index(int(dt.argmax()), dt.shape)
    return int(c), int(r)


def run_java(classes: Path, java_dir: Path, tif: Path, png: Path, jm1: int, jm2: int, eps: int,
             dil: int, t1: int, t2: int, seeds: list[tuple[int, int]], out_csv: Path) -> list[dict]:
    cp = f"{classes}:{Path(java_dir).resolve() / 'lib'}/*"
    cmd = ["java", "-Djava.awt.headless=true", "-cp", cp, DRIVER_CLASS, str(tif), str(png),
           str(jm1), str(jm2), str(eps), str(dil), str(t1), str(t2), str(out_csv),
           ";".join(f"{x},{y}" for x, y in seeds)]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0 or not Path(out_csv).exists():
        tail = " | ".join((proc.stderr or proc.stdout).strip().splitlines()[:3])
        raise GeneratorError(f"the Java driver failed: {tail}")
    with open(out_csv, newline="") as fh:
        return list(csv.DictReader(fh))


def _num(x: float) -> str:
    return repr(float(x)) if math.isfinite(float(x)) else ("nan" if math.isnan(float(x)) else "inf")


def rows_from_java(java_rows: list[dict], cell_ids: list[int], image: str, labels: str, *,
                   jm1: int, jm2: int, nucleus: int, eps: int, dil: int, t1: int, t2: int,
                   shape: tuple[int, int]) -> list[dict]:
    """Turn the driver's per-corner CSV rows into reference rows (JM1 and JM2 for each).

    ``interior`` is yes when the Java's whole edge, dilated ``dil`` times, stays inside the live
    zone of its dilation, indices [2, size-3] (README.md divergence 2).
    """
    h, w = shape
    out = []
    for jr in java_rows:
        cid = cell_ids[int(jr["cell"]) - 1]
        interior = (int(jr["minx"]) - dil >= 2 and int(jr["miny"]) - dil >= 2
                    and int(jr["maxx"]) + dil <= w - 3 and int(jr["maxy"]) + dil <= h - 3)
        contour = float(jr["contour"])
        base = {
            "image": image, "labels": labels, "jm1_channel": jm1, "jm2_channel": jm2,
            "nucleus_channel": nucleus, "cell_id": cid, "corner_method": "dp", "epsilon": eps,
            "dilation_cycles": dil, "interior": "yes" if interior else "no",
            "java_corner_row": jr["cy"], "java_corner_col": jr["cx"],
            "java_paired_row": jr["py"], "java_paired_col": jr["px"],
            "java_n_corners": jr["ncorners"], "java_corner": jr["corner"],
            "java_paired_with": jr["paired"], "seed_row": jr["seedy"], "seed_col": jr["seedx"],
            "interface_contour_px": jr["contour"], "straight_line_length_px": jr["euclid"],
            "java_distance_ratio": jr["ratio"], "interface_area_px": jr["iarea"],
            "notes": "java_reference.py",
        }
        for role, thr in (("JM1", t1), ("JM2", t2)):
            row = dict(base, role=role, threshold=thr)
            if role == "JM1":
                frag = float(jr["frag"])
                row.update(fragmented_contour_px=jr["frag"], marker_area_px=jr["m1area"],
                           marker_intensity=int(float(jr["m1int"])),
                           junction_contour_px=jr["junc_contour"],
                           junction_straight_line_px=jr["junc_euclid"])
            else:
                frag = float(jr["m2dist"])
                row.update(fragmented_contour_px=jr["m2dist"], marker_area_px=jr["m2area"],
                           marker_intensity=int(float(jr["m2int"])),
                           junction_contour_px="", junction_straight_line_px="")
            row["coverage_index"] = _num(frag / contour) if contour else "nan"
            out.append(row)
    return out


def generate(java_dir: Path, work_dir: Path, out_csv: Path, fields: list[tuple[Path, Path]],
             cells: list[int] | None = None, n_cells: int | None = None, eps: int = 2,
             dil: int = 2, t1: int = 100, t2: int = 100, jm1: int = 0, jm2: int = 1,
             nucleus: int = 2, rebuild: bool = False) -> list[dict]:
    """Run the Java over every (image, labels) field and write ``out_csv``; return its rows."""
    check_prerequisites(java_dir)
    classes = compile_java(java_dir, work_dir, rebuild)
    work_dir, out_csv = Path(work_dir), Path(out_csv)
    work_dir.mkdir(parents=True, exist_ok=True)
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    rows: list[dict] = []
    for k, (tif, npy) in enumerate(fields):
        labels = np.load(npy)
        png = edge_map.labels_to_edge_map(labels, work_dir / f"field{k}_edge_map.png")
        view = edge_map.java_view_labels(labels)
        ids = choose_cells(view, dil, cells, n_cells)
        if not ids:
            raise GeneratorError(f"no usable interior cells in {npy}")
        seeds = [seed_for(view, c) for c in ids]
        jrows = run_java(classes, java_dir, tif, png, jm1, jm2, eps, dil, t1, t2, seeds,
                         work_dir / f"field{k}_java.csv")
        rel = lambda p: Path(__import__("os").path.relpath(Path(p).resolve(), out_csv.parent.resolve())).as_posix()
        rows += rows_from_java(jrows, ids, rel(tif), rel(npy), jm1=jm1, jm2=jm2, nucleus=nucleus,
                               eps=eps, dil=dil, t1=t1, t2=t2, shape=labels.shape)
    with open(out_csv, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(HEADER)
        for r in rows:
            w.writerow([r.get(h, "") for h in HEADER])
    return rows


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--java-dir", type=Path, default=DEFAULT_JAVA_DIR,
                    help=f"Junction_Mapper checkout (default {DEFAULT_JAVA_DIR})")
    ap.add_argument("--work-dir", type=Path, required=True,
                    help="scratch directory for compiled classes and intermediate files "
                         "(must not be inside the Java checkout)")
    ap.add_argument("--out", type=Path, required=True, help="reference.csv to write")
    ap.add_argument("--image", type=Path, action="append", default=[],
                    help="RGB TIFF the Java loads (repeat with --labels, in the same order)")
    ap.add_argument("--labels", type=Path, action="append", default=[],
                    help="2-D integer .npy labels for that image")
    ap.add_argument("--control", action="store_true",
                    help="add a synthetic rectilinear grid (written next to --out)")
    ap.add_argument("--cells", type=str, default=None, help="comma-separated cell ids to click")
    ap.add_argument("--n-cells", type=int, default=None, help="click the first N interior cells")
    ap.add_argument("--epsilon", type=int, default=2)
    ap.add_argument("--dilation", type=int, default=2)
    ap.add_argument("--threshold-jm1", type=int, default=100)
    ap.add_argument("--threshold-jm2", type=int, default=100)
    ap.add_argument("--rebuild", action="store_true", help="recompile the Java even if built")
    args = ap.parse_args(argv)
    try:
        if len(args.image) != len(args.labels):
            raise GeneratorError("--image and --labels must be given the same number of times")
        fields = list(zip(args.image, args.labels))
        if args.control:
            fields.append(make_control(args.out.parent))
        if not fields:
            raise GeneratorError("nothing to do: give --image/--labels and/or --control")
        for lo, hi, name in ((1, 50, "epsilon"),):
            if not lo <= args.epsilon <= hi:
                raise GeneratorError(f"--{name} must be an integer {lo}..{hi} (the Java slider)")
        if not 1 <= args.dilation <= 9:
            raise GeneratorError("--dilation must be an integer 1..9 (the Java slider)")
        for t in (args.threshold_jm1, args.threshold_jm2):
            if not 0 <= t <= 255:
                raise GeneratorError("thresholds must be integers 0..255 (the Java sliders)")
        cells = [int(c) for c in args.cells.split(",")] if args.cells else None
        if cells is not None and len(fields) != 1:
            raise GeneratorError("--cells names label ids and needs exactly one field")
        rows = generate(args.java_dir, args.work_dir, args.out, fields, cells, args.n_cells,
                        args.epsilon, args.dilation, args.threshold_jm1, args.threshold_jm2)
        print(f"wrote {len(rows)} reference rows to {args.out}")
    except (GeneratorError, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
