#!/usr/bin/env python3
"""Generate ``tests/validation/reference.csv`` by running the original Java classes headless.

    python3 scripts/java_reference.py --java-dir /path/to/Junction_Mapper --work-dir SCRATCH \\
        --out tests/validation/reference/reference.csv \\
        [--image IMG.tif --labels IMG.JM1.npy] [--control] \\
        [--cells 3,5,8 | --n-cells 6] [--epsilon 2] [--dilation 2] \\
        [--threshold-jm1 100] [--threshold-jm2 100]

What it does: writes our labels as an edge-map PNG (``edge_map_from_labels.py``), compiles the
Java checkout into ``SCRATCH/classes`` (the Java tree is a read-only oracle: nothing is ever
written into it), then drives the REAL ``ImageUtilities.selectCell``,
``Cell_Membrane.sortEdgePixels / getDouglasPeucker``, ``Cell_Membrane_Corner`` and
``MeasurementTool`` in one JVM with ``-Djava.awt.headless=true``, exactly as steps 4 to 7 of the
GUI do, and writes one reference row per Java interface and marker role. The Java's own corner
pixel coordinates go into the row: the harness measures OUR metric functions between those same
two pixels. Cells are chosen interior (whole band clear of the Java's border dead zone).

Needs: a JDK (``java`` and ``javac`` on PATH, 11 or later) and the Java checkout, which supplies
``uk/`` (sources) and ``lib/*.jar``. Python needs only numpy, scipy and Pillow, so it runs on a
plain host Python; the Apptainer image has no JDK and does not see the Java checkout, so run this
on the host and run the tests in the image. Any missing prerequisite ends the run with one line
starting ``error:``.

``--control`` adds a synthetic grid of rectangles. Rectilinear cells are the only ones where the
Java's integer metrics are exactly comparable, so a reference without such rows leaves the
strongest assertion unused and the tests fail; a real segmentation rarely has rectilinear
cells, so always include the control.

The manual procedure in ``tests/validation/README.md`` produces the same numbers for any one
cell and is the cross-check on this generator.
"""
